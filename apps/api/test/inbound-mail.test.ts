import { describe, expect, it } from "vitest";
import {
  addressDomain,
  autoGeneratedReason,
  cleanSubject,
  inboundAuthMode,
  parseAuthResults,
  pickAuthResultsHeader,
  senderAuthenticated,
  stripQuotedReply,
  ticketNumberInSubject,
  ticketSubjectToken,
  validateSettingValue,
} from "@church/shared";

describe("ticket numbers in subjects", () => {
  it("finds the bracketed token only", () => {
    expect(ticketNumberInSubject("Re: Projector is dark [#42]")).toBe(42);
    expect(ticketNumberInSubject("[#7] New comment on ticket #7")).toBe(7);
    expect(ticketNumberInSubject("Ticket #42 is broken")).toBeNull();
    expect(ticketNumberInSubject("Re: [#0]")).toBeNull();
    expect(ticketNumberInSubject("[#12345678901234]")).toBeNull();
    expect(ticketNumberInSubject("no token")).toBeNull();
  });

  it("round-trips the token", () => {
    expect(ticketNumberInSubject(`Hello ${ticketSubjectToken(311)}`)).toBe(311);
  });
});

describe("cleaning a subject into a title", () => {
  it("drops reply prefixes and tokens", () => {
    expect(cleanSubject("Re: RE: Fwd: Projector is dark [#42]")).toBe("Projector is dark");
    expect(cleanSubject("AW: Drucker kaputt")).toBe("Drucker kaputt");
    expect(cleanSubject("Printer REQUEST")).toBe("Printer REQUEST");
  });
  it("keeps one line, and gives an empty subject a name", () => {
    expect(cleanSubject("a\r\nb\tc")).toBe("a b c");
    expect(cleanSubject("")).toBe("(no subject)");
    expect(cleanSubject("Re: [#3]")).toBe("(no subject)");
  });
  it("caps the length", () => {
    expect(cleanSubject("x".repeat(500))).toHaveLength(200);
  });
});

describe("stripping the quoted original from a reply", () => {
  it("cuts at the 'On ... wrote:' line and drops quoted lines", () => {
    const text = "Thanks, that fixed it.\n\nOn Mon, 5 Oct 2026 at 09:12, Help Desk <help@church.org> wrote:\n> Did you try the cable?\n> Let us know.\n";
    expect(stripQuotedReply(text)).toBe("Thanks, that fixed it.");
  });
  it("copes with a wrapped 'wrote:' line", () => {
    const text = "Yes please.\n\nOn Mon, 5 Oct 2026 at 09:12, Help Desk <help@church.org>\nwrote:\n> hi";
    expect(stripQuotedReply(text)).toBe("Yes please.");
  });
  it("cuts Outlook style blocks and original-message markers", () => {
    expect(stripQuotedReply("Done.\n\nFrom: Help Desk <help@church.org>\nSent: Monday\nTo: Ana\nSubject: x\n\nold")).toBe("Done.");
    expect(stripQuotedReply("Done.\n\n-----Original Message-----\nFrom: x")).toBe("Done.");
  });
  it("cuts the signature delimiter", () => {
    expect(stripQuotedReply("Ok\n-- \nAna\n07700 900123")).toBe("Ok");
  });
  it("keeps interleaved answers' own lines and collapses blank runs", () => {
    expect(stripQuotedReply("a\n\n\n\nb")).toBe("a\n\nb");
  });
  it("never returns nothing when there was text", () => {
    const quotedOnly = "> only a quote\n> and more";
    expect(stripQuotedReply(quotedOnly)).toBe(quotedOnly);
    expect(stripQuotedReply("On Mon, Ana wrote:\n> x")).toBe("On Mon, Ana wrote:\n> x");
  });
});

describe("reading Authentication-Results", () => {
  const gmail =
    "mx.google.com;\r\n       dkim=pass header.i=@church.org header.s=google header.b=abc;\r\n       spf=pass (google.com: domain of ana@church.org designates 1.2.3.4 as permitted sender) smtp.mailfrom=ana@church.org;\r\n       dmarc=pass (p=NONE sp=NONE dis=NONE) header.from=church.org";

  it("reads the server, DMARC, DKIM and SPF", () => {
    const r = parseAuthResults(gmail);
    expect(r.serverId).toBe("mx.google.com");
    expect(r.dmarc).toBe("pass");
    expect(r.dkim).toEqual([{ result: "pass", domain: "church.org" }]);
    expect(r.spf).toEqual({ result: "pass", domain: "church.org" });
  });

  it("copes with nothing and with junk", () => {
    expect(parseAuthResults(null)).toEqual({ serverId: null, dmarc: null, dkim: [], spf: null });
    expect(parseAuthResults("mx.example.org; none").dmarc).toBeNull();
  });

  it("strict wants DMARC pass", () => {
    expect(senderAuthenticated("strict", "ana@church.org", gmail)).toBe(true);
    expect(senderAuthenticated("strict", "ana@church.org", "mx.google.com; dkim=pass header.d=church.org; spf=pass smtp.mailfrom=church.org")).toBe(false);
    expect(senderAuthenticated("strict", "ana@church.org", "mx.google.com; dmarc=fail header.from=church.org")).toBe(false);
    expect(senderAuthenticated("strict", "ana@church.org", null)).toBe(false);
  });

  it("aligned accepts a DKIM or SPF pass for the sender's own domain, and not for another", () => {
    const dkimOnly = "mx.google.com; dkim=pass header.d=church.org";
    expect(senderAuthenticated("aligned", "ana@church.org", dkimOnly)).toBe(true);
    expect(senderAuthenticated("aligned", "ana@mail.church.org", dkimOnly)).toBe(true);
    expect(senderAuthenticated("aligned", "ana@church.org", "mx.google.com; dkim=pass header.d=evil.example")).toBe(false);
    expect(senderAuthenticated("aligned", "ana@church.org", "mx.google.com; spf=pass smtp.mailfrom=bounce@church.org")).toBe(true);
    expect(senderAuthenticated("aligned", "ana@church.org", "mx.google.com; spf=pass smtp.mailfrom=bounce@evil.example")).toBe(false);
    expect(senderAuthenticated("aligned", "ana@church.org", "mx.google.com; dkim=fail header.d=church.org")).toBe(false);
  });

  it("off believes the From line", () => {
    expect(senderAuthenticated("off", "ana@church.org", null)).toBe(true);
  });

  it("only believes a header written by the named server", () => {
    const forged = "evil.example; dmarc=pass header.from=church.org";
    expect(pickAuthResultsHeader([forged, gmail], "mx.google.com")).toBe(gmail);
    expect(pickAuthResultsHeader([forged], "mx.google.com")).toBeNull();
    expect(pickAuthResultsHeader([forged, gmail], "")).toBe(forged);
    expect(pickAuthResultsHeader([gmail], "google.com")).toBe(gmail);
    expect(pickAuthResultsHeader([], "mx.google.com")).toBeNull();
    expect(senderAuthenticated("strict", "ana@church.org", pickAuthResultsHeader([forged], "mx.google.com"))).toBe(false);
  });

  it("finds an address's domain", () => {
    expect(addressDomain("Ana@Church.ORG")).toBe("church.org");
    expect(addressDomain("nonsense")).toBeNull();
    expect(addressDomain("a@")).toBeNull();
  });

  it("falls back to strict for an unknown mode", () => {
    expect(inboundAuthMode("aligned")).toBe("aligned");
    expect(inboundAuthMode("whatever")).toBe("strict");
    expect(inboundAuthMode(undefined)).toBe("strict");
  });
});

describe("machine-written mail", () => {
  const h = (o: Record<string, string>) => new Map(Object.entries(o));
  it("is recognised by its headers", () => {
    expect(autoGeneratedReason(h({ "auto-submitted": "auto-replied" }))).toBe("auto_generated");
    expect(autoGeneratedReason(h({ precedence: "bulk" }))).toBe("auto_generated");
    expect(autoGeneratedReason(h({ "x-auto-response-suppress": "All" }))).toBe("auto_generated");
    expect(autoGeneratedReason(h({ "list-id": "<news.example.org>", "list-unsubscribe": "<mailto:x>" }))).toBe("auto_generated");
  });
  it("lets a person's mail through", () => {
    expect(autoGeneratedReason(h({ "auto-submitted": "no" }))).toBeNull();
    expect(autoGeneratedReason(h({ precedence: "normal" }))).toBeNull();
    expect(autoGeneratedReason(h({}))).toBeNull();
  });
});

describe("the mailbox settings", () => {
  it("validates host, port, folder, address, mode and server name", () => {
    expect(validateSettingValue("tickets.inbound.host", "imap.gmail.com")).toBeNull();
    expect(validateSettingValue("tickets.inbound.host", "imap://x")).not.toBeNull();
    expect(validateSettingValue("tickets.inbound.host", "a b")).not.toBeNull();
    expect(validateSettingValue("tickets.inbound.port", 993)).toBeNull();
    expect(validateSettingValue("tickets.inbound.port", 0)).not.toBeNull();
    expect(validateSettingValue("tickets.inbound.port", "993")).not.toBeNull();
    expect(validateSettingValue("tickets.inbound.mailbox", "INBOX")).toBeNull();
    expect(validateSettingValue("tickets.inbound.mailbox", "")).not.toBeNull();
    expect(validateSettingValue("tickets.inbound.address", "help@church.org")).toBeNull();
    expect(validateSettingValue("tickets.inbound.address", "")).toBeNull();
    expect(validateSettingValue("tickets.inbound.address", "help church")).not.toBeNull();
    expect(validateSettingValue("tickets.inbound.auth", "strict")).toBeNull();
    expect(validateSettingValue("tickets.inbound.auth", "lax")).not.toBeNull();
    expect(validateSettingValue("tickets.inbound.auth_server", "mx.google.com")).toBeNull();
    expect(validateSettingValue("tickets.inbound.auth_server", "mx google")).not.toBeNull();
  });
});
