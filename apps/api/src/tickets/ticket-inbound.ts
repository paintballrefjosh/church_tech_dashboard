const JOB = "ticket-inbound";
/** Messages handled per run; the rest wait for the next minute. */
const BATCH = 25;
/** A message that fails this many times is given up on (and logged), so one bad message cannot block the mailbox. */
const MAX_ATTEMPTS = 3;
/** On the first look at a mailbox, only mail from this long ago is taken: old mail is not a backlog of requests. */
const FIRST_RUN_WINDOW_MS = 24 * 3_600_000;
const SENDER_HOURLY_LIMIT = 30;
const LOG_RETENTION_DAYS = 90;

export interface InboundConfig {
  enabled: boolean;
  host: string;
  port: number;
  secure: boolean;
  rejectUnauthorized: boolean;
  username: string;
  password: string;
  mailbox: string;
  address: string;
  auth: InboundAuthMode;
  authServer: string;
}

export interface InboundResult {
  outcome: InboundOutcome | "duplicate";
  reason?: string;
  ticketId?: string;
}

export interface InboundRunSummary {
  state: "off" | "ok" | "error";
  handled: number;
  error?: string;
}

interface Cursor {
  uidValidity: string;
  lastUid: number;
}

interface RunStatus {
  lastRunAt: string;
  lastOkAt: string | null;
  lastError: string | null;
}

const asString = (v: unknown, fallback = ""): string => (typeof v === "string" ? v.trim() : fallback);

/**
 * Turns mail in a helpdesk mailbox into tickets and ticket comments. Read-only: it never marks, moves or deletes mail, so
 * people can use the mailbox normally. It remembers the highest message number it has handled (with the folder's UIDVALIDITY),
 * and every message is also recorded by Message-ID in `ticket_inbound_log`, which is what stops one being handled twice.
 *
 * Only accounts on this site are served, and only when the mail server confirmed the sender (INBOUND_KEYS.auth): a From line
 * proves nothing, and a message that could open tickets or comment as anyone would be an impersonation tool. Anything else is
 * logged as skipped with the reason, and nothing is ever sent back (no bounces, no auto-replies: no mail loops, no backscatter
 * to forged senders). The run is serialised across nodes by the `mutex:ticket-inbound` lease.
 */
@Injectable()
export class TicketInbound implements OnModuleInit {
  private readonly logger = new Logger(TicketInbound.name);

  constructor(
    @Inject(DB) private readonly db: Db,
    private readonly jobs: ClusterJobs,
    private readonly leases: LeaseService,
    private readonly state: JobStateService,
    private readonly settings: SettingsService,
    private readonly auth: AuthService,
    private readonly tickets: TicketsService,
    private readonly attachments: AttachmentsService,
    private readonly events: TicketEvents,
  ) {}

  onModuleInit(): void {
    this.jobs.register({ name: JOB, everyMs: 60_000, initialDelayMs: 40_000, run: async () => void (await this.run()) });
  }

  // ---- configuration ----

  async config(): Promise<InboundConfig> {
    const get = (k: string) => this.settings.get(k).catch(() => undefined);
    const [enabled, host, port, secure, reject, username, password, mailbox, address, auth, authServer] = await Promise.all([
      get(INBOUND_KEYS.enabled),
      get(INBOUND_KEYS.host),
      get(INBOUND_KEYS.port),
      get(INBOUND_KEYS.secure),
      get(INBOUND_KEYS.rejectUnauthorized),
      get(INBOUND_KEYS.username),
      get(INBOUND_KEYS.password),
      get(INBOUND_KEYS.mailbox),
      get(INBOUND_KEYS.address),
      get(INBOUND_KEYS.auth),
      get(INBOUND_KEYS.authServer),
    ]);
    return {
      enabled: enabled === true,
      host: asString(host),
      port: typeof port === "number" && port > 0 ? port : 993,
      secure: secure !== false,
      rejectUnauthorized: reject !== false,
      username: asString(username),
      password: typeof password === "string" ? password : "",
      mailbox: asString(mailbox) || "INBOX",
      address: asString(address).toLowerCase(),
      auth: inboundAuthMode(auth),
      authServer: asString(authServer),
    };
  }

  private complete(c: InboundConfig): boolean {
    return c.host !== "" && c.username !== "" && c.password !== "";
  }

  // ---- the run ----

  /** One pass over the mailbox. `force` runs even while the switch is off (the Check now and Test buttons). */
  async run(opts: { force?: boolean } = {}): Promise<InboundRunSummary> {
    const cfg = await this.config();
    if ((!cfg.enabled && !opts.force) || !this.complete(cfg)) return { state: "off", handled: 0 };
    const locked = await this.leases.withMutex("ticket-inbound", 120, () => this.runLocked(cfg));
    if (!locked.ran) return { state: "ok", handled: 0 };
    return locked.value;
  }

  private async runLocked(cfg: InboundConfig): Promise<InboundRunSummary> {
    const now = new Date().toISOString();
    const previous = (await this.state.get<RunStatus>(JOB, "status"))?.value ?? null;
    let summary: InboundRunSummary;
    try {
      const handled = await this.poll(cfg);
      summary = { state: "ok", handled };
      await this.state.set(JOB, "status", { lastRunAt: now, lastOkAt: now, lastError: null } satisfies RunStatus);
    } catch (err) {
      const message = this.describeError(err, cfg);
      summary = { state: "error", handled: 0, error: message };
      if (previous?.lastError !== message) this.logger.warn(`helpdesk mailbox: ${message}`);
      await this.state.set(JOB, "status", { lastRunAt: now, lastOkAt: previous?.lastOkAt ?? null, lastError: message } satisfies RunStatus);
    }
    await this.prune().catch(() => undefined);
    return summary;
  }

  private client(cfg: InboundConfig): ImapFlow {
    const client = new ImapFlow({
      host: cfg.host,
      port: cfg.port,
      secure: cfg.secure,
      auth: { user: cfg.username, pass: cfg.password },
      logger: false,
      tls: { rejectUnauthorized: cfg.rejectUnauthorized },
      connectionTimeout: 15_000,
      greetingTimeout: 15_000,
      socketTimeout: 60_000,
      maxLiteralSize: INBOUND_MAX_MESSAGE_BYTES,
    });
    // A connection that breaks later must not take the process down: the next run starts a new one.
    client.on("error", () => undefined);
    return client;
  }

  private describeError(err: unknown, cfg: InboundConfig): string {
    const e = err as { message?: string; responseText?: string; code?: string; authenticationFailed?: boolean };
    let m = e.authenticationFailed ? "The mailbox refused the login." : e.responseText || e.message || String(err);
    if (e.code === "ENOTFOUND") m = `Could not find the server ${cfg.host}.`;
    else if (e.code === "ECONNREFUSED") m = `${cfg.host}:${cfg.port} refused the connection.`;
    else if (e.code === "ETIMEDOUT" || /timeout/i.test(m)) m = `${cfg.host}:${cfg.port} did not answer in time.`;
    return m.replace(cfg.password, "[hidden]").slice(0, 300);
  }

  /** Connect and handle new mail; returns how many messages were looked at. */
  private async poll(cfg: InboundConfig): Promise<number> {
    const client = this.client(cfg);
    await client.connect();
    let handled = 0;
    try {
      const lock = await client.getMailboxLock(cfg.mailbox, { readOnly: true });
      try {
        const box = client.mailbox;
        if (!box) throw new Error(`The folder "${cfg.mailbox}" could not be opened.`);
        const uidValidity = String(box.uidValidity);
        const stored = (await this.state.get<Cursor>(JOB, "cursor"))?.value ?? null;
        const sameFolder = stored !== null && stored.uidValidity === uidValidity;

        // A known position: everything after it. Otherwise (first look, or the folder was rebuilt) only recent mail; the log
        // stops any of it being handled twice.
        const found = sameFolder
          ? await client.search({ uid: `${stored.lastUid + 1}:*` }, { uid: true })
          : await client.search({ since: new Date(Date.now() - FIRST_RUN_WINDOW_MS) }, { uid: true });
        const uids = (found || []).filter((u) => !sameFolder || u > stored.lastUid).sort((a, b) => a - b);
        // Messages that arrive after the folder was opened get a UID of uidNext or more, so everything below it that exists is
        // in `found` and, once handled, the position can move to the end of the folder (that is also how the history older
        // than the first-run window is left behind).
        const endOfFolder = Math.max(0, Number(box.uidNext) - 1);
        let position = sameFolder ? stored.lastUid : 0;
        for (const uid of uids.slice(0, BATCH)) {
          if (!(await this.handleUid(client, cfg, uidValidity, uid))) break;
          position = uid;
          handled++;
          await this.state.set(JOB, "cursor", { uidValidity, lastUid: position } satisfies Cursor);
        }
        if (handled === uids.length) {
          await this.state.set(JOB, "cursor", { uidValidity, lastUid: Math.max(position, endOfFolder) } satisfies Cursor);
        }
      } finally {
        lock.release();
      }
    } finally {
      await client.logout().catch(() => client.close());
    }
    return handled;
  }

  /** Fetch and handle one message. False when it failed and should be tried again (the run stops there). */
  private async handleUid(client: ImapFlow, cfg: InboundConfig, uidValidity: string, uid: number): Promise<boolean> {
    const fallbackId = `imap:${cfg.mailbox}:${uidValidity}:${uid}`;
    let from = "";
    let subject = "";
    try {
      const head = await client.fetchOne(String(uid), { uid: true, size: true, envelope: true }, { uid: true });
      if (!head) return true;
      from = head.envelope?.from?.[0]?.address?.toLowerCase() ?? "";
      subject = head.envelope?.subject ?? "";
      if ((head.size ?? 0) > INBOUND_MAX_MESSAGE_BYTES) {
        await this.record(fallbackId, from, subject, "skipped", "too_large", null);
        return true;
      }
      const msg = await client.fetchOne(String(uid), { uid: true, source: true }, { uid: true });
      if (!msg || !msg.source) return true;
      await this.processMessage(msg.source, cfg);
      return true;
    } catch (err) {
      const attempts = await this.recordFailure(fallbackId, from, subject, (err as Error).message);
      this.logger.warn(`helpdesk mailbox: message ${uid} failed (attempt ${attempts}): ${(err as Error).message}`);
      return attempts >= MAX_ATTEMPTS;
    }
  }

  // ---- one message ----

  /** Turn one raw message into a ticket or a comment, or record why not. Public for the tests; the run is the only caller. */
  async processMessage(source: Buffer, cfg: InboundConfig): Promise<InboundResult> {
    const mail = await simpleParser(source);
    const messageId = this.messageIdOf(mail, source);
    if (await this.seen(messageId)) return { outcome: "duplicate" };

    const from = (mail.from?.value[0]?.address ?? "").trim().toLowerCase();
    const subject = (mail.subject ?? "").trim();
    const skip = async (reason: InboundSkipReason): Promise<InboundResult> => {
      await this.record(messageId, from, subject, "skipped", reason, null);
      return { outcome: "skipped", reason };
    };

    if (!from) return skip("no_sender");
    if (await this.isOwnAddress(from, cfg)) return skip("own_mail");
    const headers = new Map<string, string>();
    for (const line of mail.headerLines ?? []) {
      if (!headers.has(line.key)) headers.set(line.key, line.line.slice(line.key.length + 1).trim());
    }
    const auto = autoGeneratedReason(headers);
    if (auto) return skip(auto);

    const sender = await this.findSender(from);
    if (!sender) return skip("unknown_sender");

    const resultsHeaders = (mail.headerLines ?? [])
      .filter((l) => l.key === "authentication-results")
      .map((l) => l.line.slice(l.line.indexOf(":") + 1).trim());
    if (!senderAuthenticated(cfg.auth, from, pickAuthResultsHeader(resultsHeaders, cfg.authServer))) return skip("not_authenticated");

    if (!sender.permissions.includes("tickets:write:own")) return skip("no_access");
    if ((await this.recentFrom(from)) >= SENDER_HOURLY_LIMIT) return skip("rate_limited");

    const text = (mail.text ?? "").replace(/\r\n?/g, "\n");
    const files = (mail.attachments ?? []).filter((a) => !a.related && a.content?.length);
    if (text.trim() === "" && files.length === 0) return skip("empty");

    // A reply to a ticket mail names the ticket in its subject.
    const number = ticketNumberInSubject(subject);
    if (number !== null) {
      const [ticket] = await this.db.select({ id: tickets.id }).from(tickets).where(eq(tickets.number, number)).limit(1);
      if (ticket) {
        const readable = await this.tickets.getById(sender, ticket.id).catch(() => null);
        if (readable) {
          const before = readable.status;
          const body = this.limit(stripQuotedReply(text) || "(attachment)");
          const comment = await this.tickets.addComment(sender, readable.id, { body, isInternal: false });
          await this.attach(readable.id, sender, files);
          const after = await this.tickets.getById(sender, readable.id);
          this.events.commented(sender, after, comment, before);
          await this.record(messageId, from, subject, "comment", null, readable.id);
          return { outcome: "comment", ticketId: readable.id };
        }
      }
      // An unknown or unreadable ticket number: the message is still a request for help, so it opens a new ticket.
    }

    const created = await this.tickets.create(sender, {
      title: cleanSubject(subject),
      description: this.limit(text.trim() || "(see the attachments)"),
      priority: "normal",
    });
    await this.tickets.logEvent(created.id, sender, `${sender.name ?? sender.email} opened this ticket by email`);
    await this.attach(created.id, sender, files);
    this.events.created(created);
    await this.record(messageId, from, subject, "ticket", null, created.id);
    return { outcome: "ticket", ticketId: created.id };
  }

  private limit(body: string): string {
    return body.length > INBOUND_BODY_MAX ? `${body.slice(0, INBOUND_BODY_MAX)}\n\n[The rest of the message was cut off.]` : body;
  }

  private messageIdOf(mail: ParsedMail, source: Buffer): string {
    const id = (mail.messageId ?? "").trim();
    if (id) return id.slice(0, 500);
    // No Message-ID: a hash of the message itself still tells the same message apart across folders and re-fetches.
    return `sha256:${createHash("sha256").update(source).digest("hex")}`;
  }

  private async isOwnAddress(from: string, cfg: InboundConfig): Promise<boolean> {
    const smtp = asString(await this.settings.get("smtp.from_email").catch(() => ""), "").toLowerCase();
    return [smtp, cfg.address, cfg.username.toLowerCase()].some((a) => a !== "" && a === from);
  }

  private async findSender(address: string): Promise<AuthenticatedUser | null> {
    const [row] = await this.db
      .select({ id: users.id, isActive: users.isActive, deletedAt: users.deletedAt, approval: users.approvalStatus })
      .from(users)
      .where(eq(users.email, address))
      .limit(1);
    if (!row || !row.isActive || row.deletedAt || row.approval !== "approved") return null;
    return this.auth.loadUserById(row.id);
  }

  /** Store each file as an attachment; say in the ticket what could not be. */
  private async attach(ticketId: string, sender: AuthenticatedUser, files: NonNullable<ParsedMail["attachments"]>): Promise<void> {
    const notAttached: string[] = [];
    let count = 0;
    for (const f of files) {
      const name = f.filename || "attachment";
      if (count >= INBOUND_MAX_ATTACHMENTS) {
        notAttached.push(`${name} (too many files)`);
        continue;
      }
      if (f.size > MAX_ATTACHMENT_BYTES) {
        notAttached.push(`${name} (too large)`);
        continue;
      }
      try {
        await this.attachments.upload("ticket", ticketId, sender.id, {
          filename: name,
          mimetype: (f.contentType || "").toLowerCase(),
          stream: Readable.from(f.content),
          sizeLimit: 0,
        });
        count++;
      } catch (err) {
        const why = (err as { message?: string }).message ?? "";
        notAttached.push(`${name} (${/not allowed/i.test(why) ? "file type not allowed" : "could not be stored"})`);
      }
    }
    if (notAttached.length > 0) await this.tickets.logEvent(ticketId, sender, `Not attached from the email: ${notAttached.join(", ")}`);
  }

  // ---- the log ----

  private async seen(messageId: string): Promise<boolean> {
    const [row] = await this.db
      .select({ outcome: ticketInboundLog.outcome, attempts: ticketInboundLog.attempts })
      .from(ticketInboundLog)
      .where(eq(ticketInboundLog.messageId, messageId))
      .limit(1);
    // A failed message is tried again until it runs out of attempts.
    return !!row && !(row.outcome === "error" && row.attempts < MAX_ATTEMPTS);
  }

  private async record(
    messageId: string,
    from: string,
    subject: string,
    outcome: InboundOutcome,
    reason: string | null,
    ticketId: string | null,
  ): Promise<void> {
    await this.db
      .insert(ticketInboundLog)
      .values({ messageId, fromAddress: from.slice(0, 320), subject: subject.slice(0, 200), outcome, reason, ticketId })
      .onConflictDoUpdate({
        target: ticketInboundLog.messageId,
        set: { outcome, reason, ticketId, handledAt: new Date() },
      });
  }

  /** Count a failed attempt; returns how many have been made. */
  private async recordFailure(messageId: string, from: string, subject: string, reason: string): Promise<number> {
    const [row] = await this.db
      .insert(ticketInboundLog)
      .values({ messageId, fromAddress: from.slice(0, 320), subject: subject.slice(0, 200), outcome: "error", reason: reason.slice(0, 300), attempts: 1 })
      .onConflictDoUpdate({
        target: ticketInboundLog.messageId,
        set: { outcome: "error", reason: reason.slice(0, 300), attempts: sql`${ticketInboundLog.attempts} + 1`, handledAt: new Date() },
      })
      .returning({ attempts: ticketInboundLog.attempts });
    return Number(row?.attempts ?? 1);
  }

  private async recentFrom(address: string): Promise<number> {
    const [row] = await this.db
      .select({ n: sql<number>`count(*)` })
      .from(ticketInboundLog)
      .where(
        and(
          eq(ticketInboundLog.fromAddress, address),
          inArray(ticketInboundLog.outcome, ["ticket", "comment"]),
          gte(ticketInboundLog.handledAt, new Date(Date.now() - 3_600_000)),
        ),
      );
    return Number(row?.n ?? 0);
  }

  private async prune(): Promise<void> {
    const cutoff = new Date(Date.now() - LOG_RETENTION_DAYS * 86_400_000);
    await deleteInBatches(async (limit) => {
      const old = this.db.select({ id: ticketInboundLog.id }).from(ticketInboundLog).where(lt(ticketInboundLog.handledAt, cutoff)).limit(limit);
      const removed = await this.db.delete(ticketInboundLog).where(inArray(ticketInboundLog.id, old)).returning({ id: ticketInboundLog.id });
      return removed.length;
    });
  }

  // ---- for the settings page ----

  /** Connect, open the folder and say how many messages it holds. Never reads or stores any of them. */
  async test(): Promise<{ ok: boolean; message: string }> {
    const cfg = await this.config();
    if (!this.complete(cfg)) return { ok: false, message: "Enter the server, the login and the password first." };
    const client = this.client(cfg);
    try {
      await client.connect();
      const lock = await client.getMailboxLock(cfg.mailbox, { readOnly: true });
      try {
        const n = client.mailbox ? client.mailbox.exists : 0;
        return { ok: true, message: `Connected as ${cfg.username}. The folder "${cfg.mailbox}" holds ${n} message${n === 1 ? "" : "s"}.` };
      } finally {
        lock.release();
      }
    } catch (err) {
      return { ok: false, message: this.describeError(err, cfg) };
    } finally {
      await client.logout().catch(() => client.close());
    }
  }

  async status() {
    const cfg = await this.config();
    const since = new Date(Date.now() - 7 * 86_400_000);
    const [run, counts, recent] = await Promise.all([
      this.state.get<RunStatus>(JOB, "status"),
      this.db
        .select({ outcome: ticketInboundLog.outcome, n: sql<number>`count(*)` })
        .from(ticketInboundLog)
        .where(gte(ticketInboundLog.handledAt, since))
        .groupBy(ticketInboundLog.outcome),
      this.db
        .select({
          id: ticketInboundLog.id,
          handledAt: ticketInboundLog.handledAt,
          fromAddress: ticketInboundLog.fromAddress,
          subject: ticketInboundLog.subject,
          outcome: ticketInboundLog.outcome,
          reason: ticketInboundLog.reason,
          ticketId: ticketInboundLog.ticketId,
        })
        .from(ticketInboundLog)
        .orderBy(desc(ticketInboundLog.handledAt))
        .limit(50),
    ]);
    const byOutcome = { ticket: 0, comment: 0, skipped: 0, error: 0 };
    for (const c of counts) if (c.outcome in byOutcome) byOutcome[c.outcome as keyof typeof byOutcome] = Number(c.n);
    return {
      enabled: cfg.enabled,
      configured: this.complete(cfg) && cfg.address !== "",
      address: cfg.address,
      auth: cfg.auth,
      authServer: cfg.authServer,
      lastRunAt: run?.value.lastRunAt ?? null,
      lastOkAt: run?.value.lastOkAt ?? null,
      lastError: run?.value.lastError ?? null,
      week: byOutcome,
      recent: recent.map((r) => ({
        ...r,
        handledAt: r.handledAt.toISOString(),
        reasonText: r.reason && r.reason in INBOUND_SKIP_REASONS ? INBOUND_SKIP_REASONS[r.reason as InboundSkipReason] : r.reason,
      })),
    };
  }
}
